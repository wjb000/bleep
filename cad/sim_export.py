"""Write sim/bleep.urdf, sim/bleep.xml (MuJoCo) and sim/meshes/*.obj from the CAD build (called by export.py)."""
import os, json, numpy as np, trimesh
import bleep
from textmesh import write_obj
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
SIM = os.path.join(ROOT, 'sim')

# STS3215-C001 (7.4 V version) on a 2S LiFePO4 pack (6.4 V nominal). Priors only: sim/sysid.py fits kp/damping/friction/armature.
SERVO = dict(stall_nm=1.65,            # 19.5 kg.cm @ 7.4 V scaled to 6.4 V (Feetech lists 19.5 kg.cm; we derate to the pack voltage)
             noload_rad_s=4.8,         # 0.192 s / 60 deg @ 7.4 V -> 5.45 rad/s, scaled to 6.4 V
             kp=12.0, damping=0.08, frictionloss=0.05, armature=0.02)
HOME = {'hip_yaw': 0.0, 'hip_roll': 0.0, 'hip_pitch': -0.42, 'knee': 0.84, 'ankle': -0.42, 'neck_yaw': 0.0}

def home_q(jn):
    for k, v in HOME.items():
        if jn.endswith(k):
            return v
    return 0.0

def f(v, n=5):
    return ' '.join(f'{x:.{n}g}' if abs(x) > 1e-12 else '0' for x in v)

def link_mesh(l, parts, meshes, servos, smesh, E, origin):
    ms = [meshes[p['name']] for p in parts if p['link'] == l]
    for s in servos:
        own = next(p for p in parts if s.name in p['servos'])
        if own['link'] == l:
            ms.append(smesh[s.name])
    m = trimesh.util.concatenate(ms)
    m = m.copy(); m.apply_translation(-origin[l]); m.apply_scale(0.001)
    return m

def collision_boxes(l, parts, meshes, origin):
    """one box per printed part of the link (feet: the sole only)"""
    out = []
    for p in parts:
        if p['link'] != l:
            continue
        b = meshes[p['name']].bounds.copy()
        if p['name'].endswith('foot'):
            b[1][2] = bleep.SOLE
            out.append((p['name'].replace('_foot', '_foot_sole'), b))
        elif p['name'].startswith('head'):
            if p['name'] == 'head_shell':
                out.append(('head_dome', b))
        elif p['name'] == 'body_lid':
            b[0][2] = bleep.Z_SPLIT; out.append(('body_lid', b))
        else:
            out.append((p['name'], b))
    return [(n, ((b[0] + b[1]) / 2 - origin[l]) / 1000, (b[1] - b[0]) / 2000) for n, b in out]

def write(parts, meshes, servos, smesh, E, J, origin, LP, links):
    os.makedirs(os.path.join(SIM, 'meshes'), exist_ok=True)
    for l in links:
        write_obj(link_mesh(l, parts, meshes, servos, smesh, E, origin), os.path.join(SIM, 'meshes', l + '.obj'))
    lim = {j: np.radians(bleep.limit_deg(j)) for j in J}
    # ---------------- URDF
    U = ['<?xml version="1.0"?>', '<robot name="bleep">']
    for l in links:
        p = LP[l]; I = np.array(p['I_kgm2'])
        U += [f'  <link name="{l}">',
              f'    <inertial><origin xyz="{f(p["com_m"])}"/><mass value="{p["mass_kg"]:.4f}"/>'
              f'<inertia ixx="{I[0,0]:.4e}" ixy="{I[0,1]:.4e}" ixz="{I[0,2]:.4e}" iyy="{I[1,1]:.4e}" iyz="{I[1,2]:.4e}" izz="{I[2,2]:.4e}"/></inertial>',
              f'    <visual><geometry><mesh filename="meshes/{l}.obj"/></geometry></visual>']
        for n, c, h in collision_boxes(l, parts, meshes, origin):
            U.append(f'    <collision name="{n}"><origin xyz="{f(c)}"/><geometry><box size="{f(2 * h)}"/></geometry></collision>')
        U.append('  </link>')
    for jn, (pa, c, o, a) in J.items():
        rel = (np.array(o) - origin[pa]) / 1000
        U.append(f'  <joint name="{jn}" type="revolute"><parent link="{pa}"/><child link="{c}"/><origin xyz="{f(rel)}"/><axis xyz="{f(a)}"/>'
                 f'<limit lower="{lim[jn][0]:.4f}" upper="{lim[jn][1]:.4f}" effort="{SERVO["stall_nm"]}" velocity="{SERVO["noload_rad_s"]}"/></joint>')
    U.append('</robot>')
    open(os.path.join(SIM, 'bleep.urdf'), 'w').write('\n'.join(U) + '\n')

    # ---------------- MJCF
    kids = {l: [] for l in links}
    jof = {}
    for jn, (pa, c, o, a) in J.items():
        kids[pa].append(c); jof[c] = (jn, o, a)
    side_bits = lambda l: ('contype="1" conaffinity="4"' if l.startswith('l_') else 'contype="5" conaffinity="0"' if l.startswith('r_') else 'contype="1" conaffinity="0"')
    X = ['<mujoco model="bleep">',
         '  <!-- generated by cad/export.py from the CAD: masses/inertias are CAD volumes x PLA + datasheet masses of bought parts -->',
         '  <compiler angle="radian" meshdir="meshes" autolimits="true"/>',
         '  <option timestep="0.002" integrator="implicitfast" cone="elliptic" impratio="5"/>',
         '  <default>',
         f'    <default class="sts3215"><joint armature="{SERVO["armature"]}" damping="{SERVO["damping"]}" frictionloss="{SERVO["frictionloss"]}"/>'
         f'<position kp="{SERVO["kp"]}" forcerange="-{SERVO["stall_nm"]} {SERVO["stall_nm"]}"/></default>',
         '    <default class="visual"><geom type="mesh" contype="0" conaffinity="0" group="1" density="0"/></default>',
         '    <default class="col"><geom type="box" group="3" density="0" friction="0.8 0.02 0.01" solref="0.004 1"/></default>',
         '  </default>',
         '  <asset>']
    for l in links:
        X.append(f'    <mesh name="{l}" file="{l}.obj"/>')
    X += ['    <texture name="grid" type="2d" builtin="checker" rgb1=".18 .2 .23" rgb2=".24 .26 .3" width="512" height="512"/>',
          '    <material name="grid" texture="grid" texrepeat="8 8" reflectance="0.05"/>',
          '    <material name="shell" rgba=".91 .89 .84 1"/>',
          '  </asset>',
          '  <worldbody>',
          '    <light pos="0 0 3" dir="0 0 -1" directional="true"/>',
          '    <geom name="floor" type="plane" size="0 0 0.05" material="grid" contype="1" conaffinity="1" friction="0.8 0.02 0.01"/>']
    imu = next(e for e in E if e['key'] == 'imu')
    imu_p = (imu['mesh'].bounds.mean(0)) / 1000

    def body(l, ind):
        p = LP[l]; I = np.array(p['I_kgm2'])
        sp = '  ' * ind
        out = []
        if l == 'base':
            out.append(f'{sp}<body name="base" pos="0 0 0.02">')
            out.append(f'{sp}  <freejoint name="root"/>')
            out.append(f'{sp}  <site name="imu" pos="{f(imu_p)}" size="0.004"/>')
        else:
            jn, o, a = jof[l]
            pa = next(k for k, v in kids.items() if l in v)
            rel = (np.array(o) - origin[pa]) / 1000
            out.append(f'{sp}<body name="{l}" pos="{f(rel)}">')
            out.append(f'{sp}  <joint name="{jn}" class="sts3215" axis="{f(a)}" range="{lim[jn][0]:.4f} {lim[jn][1]:.4f}"/>')
        out.append(f'{sp}  <inertial pos="{f(p["com_m"])}" mass="{p["mass_kg"]:.4f}" fullinertia="{I[0,0]:.4e} {I[1,1]:.4e} {I[2,2]:.4e} {I[0,1]:.4e} {I[0,2]:.4e} {I[1,2]:.4e}"/>')
        out.append(f'{sp}  <geom class="visual" mesh="{l}" material="shell"/>')
        for n, c, h in collision_boxes(l, parts, meshes, origin):
            out.append(f'{sp}  <geom name="{n}" class="col" pos="{f(c)}" size="{f(h)}" {side_bits(l)}/>')
        for k in kids[l]:
            out += body(k, ind + 1)
        out.append(f'{sp}</body>')
        return out
    X += body('base', 2)
    X.append('  </worldbody>')
    X.append('  <actuator>')
    for jn in J:
        X.append(f'    <position name="{jn}" joint="{jn}" class="sts3215" ctrlrange="{lim[jn][0]:.4f} {lim[jn][1]:.4f}"/>')
    X.append('  </actuator>')
    X += ['  <sensor>', '    <framequat name="imu_quat" objtype="site" objname="imu"/>', '    <gyro name="imu_gyro" site="imu"/>',
          '    <accelerometer name="imu_acc" site="imu"/>', '  </sensor>', '</mujoco>']
    xml = '\n'.join(X) + '\n'
    open(os.path.join(SIM, 'bleep.xml'), 'w').write(xml)
    # home keyframe: put the soles on the floor in the crouched home pose
    import mujoco
    m = mujoco.MjModel.from_xml_path(os.path.join(SIM, 'bleep.xml')); dd = mujoco.MjData(m)
    q = np.zeros(m.nq); q[3] = 1
    for jn in J:
        q[m.jnt_qposadr[m.joint(jn).id]] = home_q(jn)
    dd.qpos[:] = q; mujoco.mj_forward(m, dd)
    soles = [m.geom('l_foot_sole').id, m.geom('r_foot_sole').id]
    zmin = min(dd.geom_xpos[g][2] - m.geom_size[g][2] for g in soles)
    q[2] = 0.02 - zmin + 0.0005
    ctrl = [home_q(jn) for jn in J]
    xml = xml.replace('  <sensor>', f'  <keyframe>\n    <key name="home" qpos="{f(q, 6)}" ctrl="{f(ctrl, 6)}"/>\n  </keyframe>\n  <sensor>')
    open(os.path.join(SIM, 'bleep.xml'), 'w').write(xml)
    json.dump({jn: home_q(jn) for jn in J}, open(os.path.join(SIM, 'home_pose.json'), 'w'), indent=1)
    json.dump(SERVO, open(os.path.join(SIM, 'servo_prior.json'), 'w'), indent=1)
    print('wrote sim/bleep.urdf, sim/bleep.xml, sim/meshes/*')
