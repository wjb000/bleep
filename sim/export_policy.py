#!/usr/bin/env python3
"""Export the PPO actor (deterministic mean) to firmware/bleep/policy_weights.h (float32 C arrays) + policy.npz.
The firmware runs exactly: a = W3 @ elu(W2 @ elu(W1 @ obs + b1) + b2) + b3, then clips to [-1, 1]."""
import os, sys, numpy as np

def cf(x):
    t = f'{float(x):.7g}'
    return (t if ('.' in t or 'e' in t or 'n' in t) else t + '.0') + 'f'

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import env as E

def export(model_zip, out_h=os.path.join(ROOT, 'firmware', 'bleep', 'policy_weights.h')):
    from stable_baselines3 import PPO
    model = PPO.load(model_zip, device='cpu')
    sd = model.policy.state_dict()
    Ws = [sd['mlp_extractor.policy_net.0.weight'], sd['mlp_extractor.policy_net.2.weight'], sd['action_net.weight']]
    bs = [sd['mlp_extractor.policy_net.0.bias'], sd['mlp_extractor.policy_net.2.bias'], sd['action_net.bias']]
    Ws = [w.numpy().astype(np.float32) for w in Ws]; bs = [b.numpy().astype(np.float32) for b in bs]
    np.savez(os.path.join(os.path.dirname(model_zip), 'policy.npz'), W1=Ws[0], b1=bs[0], W2=Ws[1], b2=bs[1], W3=Ws[2], b3=bs[2])
    import json as _j   # text copy for the repo (the .npz / .zip are binary and not committed)
    _j.dump({k: v.tolist() for k, v in dict(W1=Ws[0], b1=bs[0], W2=Ws[1], b2=bs[1], W3=Ws[2], b3=bs[2]).items()},
            open(os.path.join(os.path.dirname(model_zip), 'policy.json'), 'w'))
    L = ['// generated by sim/export_policy.py from ' + os.path.basename(model_zip), '#pragma once',
         f'#define POLICY_OBS {Ws[0].shape[1]}', f'#define POLICY_H1 {Ws[0].shape[0]}', f'#define POLICY_H2 {Ws[1].shape[0]}', f'#define POLICY_ACT {Ws[2].shape[0]}',
         f'#define ACTION_SCALE {cf(E.ACTION_SCALE)}', f'#define GAIT_PERIOD {cf(E.GAIT_PERIOD)}', f'#define DQ_SCALE {cf(E.DQ_SCALE)}',
         'static const float CMD_SCALE[3] = {' + ', '.join(cf(x) for x in E.CMD_SCALE) + '};']
    import json
    home = json.load(open(os.path.join(HERE, 'home_pose.json')))
    L.append('static const float Q_HOME[10] = {' + ', '.join(cf(home[n]) for n in E.LEG) + '};')
    for i, (w, b) in enumerate(zip(Ws, bs), 1):
        L.append(f'static const float PW{i}[{w.shape[0]}][{w.shape[1]}] = {{')
        L += ['  {' + ', '.join(cf(x) for x in row) + '},' for row in w]
        L.append('};')
        L.append(f'static const float PB{i}[{b.shape[0]}] = {{' + ', '.join(cf(x) for x in b) + '};')
    os.makedirs(os.path.dirname(out_h), exist_ok=True)
    open(out_h, 'w').write('\n'.join(L) + '\n')
    print('wrote', out_h, f'({sum(w.size + b.size for w, b in zip(Ws, bs))} params)')

if __name__ == '__main__':
    export(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'runs', 'walk', 'model.zip'))
